"""TCP transport-layer summary analyzer.

This module reads packet-level JSONL records generated by Step 3 and writes a
basic TCP summary. It does not call dumpcap, tshark, or perform application
layer analysis.
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path
from typing import Any

from packet_collector.analyzers.common import (
    any_field_non_empty,
    as_float,
    as_int,
    count_value,
    counter_dict,
    duration,
    iter_jsonl_records,
    non_empty,
    protocol_seen,
    throughput_bps,
)
from packet_collector.storage.json_writer import write_json


def _new_stream_summary() -> dict[str, Any]:
    """Create an empty TCP stream summary accumulator."""
    return {
        "packet_count": 0,
        "frame_bytes": 0,
        "tcp_payload_bytes": 0,
        "first_time_epoch": None,
        "last_time_epoch": None,
        "duration_sec": None,
        "src_ips": Counter(),
        "dst_ips": Counter(),
        "src_ports": Counter(),
        "dst_ports": Counter(),
    }


def _finalize_streams(streams: dict[str, dict[str, Any]]) -> dict[str, dict[str, object]]:
    """Convert stream accumulators to JSON-serializable summaries."""
    finalized: dict[str, dict[str, object]] = {}
    for stream_id, stream in sorted(streams.items()):
        stream_duration = duration(stream["first_time_epoch"], stream["last_time_epoch"])
        finalized[stream_id] = {
            "packet_count": stream["packet_count"],
            "frame_bytes": stream["frame_bytes"],
            "tcp_payload_bytes": stream["tcp_payload_bytes"],
            "first_time_epoch": stream["first_time_epoch"],
            "last_time_epoch": stream["last_time_epoch"],
            "duration_sec": stream_duration,
            "src_ips": counter_dict(stream["src_ips"]),
            "dst_ips": counter_dict(stream["dst_ips"]),
            "src_ports": counter_dict(stream["src_ports"]),
            "dst_ports": counter_dict(stream["dst_ports"]),
        }
    return finalized


def _is_tcp_record(record: dict[str, Any]) -> bool:
    """Return True when a mixed JSONL record belongs to TCP."""
    return protocol_seen(record, "tcp") or any_field_non_empty(
        record,
        [
            "tcp_len",
            "tcp_flags",
            "tcp_stream",
            "tcp_retransmission",
            "tcp_fast_retransmission",
            "tcp_out_of_order",
            "tcp_ack_rtt",
        ],
    )


def analyze_tcp_jsonl(packet_jsonl: Path, output_file: Path) -> Path:
    """Analyze TCP packet JSONL and write `tcp_summary.json`."""
    packet_count = 0
    invalid_record_count = 0
    first_time_epoch: float | None = None
    last_time_epoch: float | None = None
    total_frame_bytes = 0
    total_tcp_payload_bytes = 0
    retransmission_count = 0
    fast_retransmission_count = 0
    out_of_order_count = 0
    ack_rtts: list[float] = []

    src_ip_counts: Counter[str] = Counter()
    dst_ip_counts: Counter[str] = Counter()
    src_port_counts: Counter[str] = Counter()
    dst_port_counts: Counter[str] = Counter()
    tcp_flags_counts: Counter[str] = Counter()
    streams: dict[str, dict[str, Any]] = {}

    for record, invalid in iter_jsonl_records(packet_jsonl):
        if invalid or record is None:
            invalid_record_count += 1
            continue
        if not _is_tcp_record(record):
            continue

        packet_count += 1
        time_epoch = as_float(record.get("time_epoch"))
        if time_epoch is not None:
            if first_time_epoch is None:
                first_time_epoch = time_epoch
            last_time_epoch = time_epoch

        frame_len = as_int(record.get("frame_len"))
        tcp_len = as_int(record.get("tcp_len"))
        total_frame_bytes += frame_len
        total_tcp_payload_bytes += tcp_len

        count_value(src_ip_counts, record.get("src_ip"))
        count_value(dst_ip_counts, record.get("dst_ip"))
        count_value(src_port_counts, record.get("src_port"))
        count_value(dst_port_counts, record.get("dst_port"))
        count_value(tcp_flags_counts, record.get("tcp_flags"))

        if non_empty(record.get("tcp_retransmission")):
            retransmission_count += 1
        if non_empty(record.get("tcp_fast_retransmission")):
            fast_retransmission_count += 1
        if non_empty(record.get("tcp_out_of_order")):
            out_of_order_count += 1

        ack_rtt = as_float(record.get("tcp_ack_rtt"))
        if ack_rtt is not None:
            ack_rtts.append(ack_rtt)

        stream_id = str(record.get("tcp_stream") if non_empty(record.get("tcp_stream")) else "unknown")
        stream = streams.setdefault(stream_id, _new_stream_summary())
        stream["packet_count"] += 1
        stream["frame_bytes"] += frame_len
        stream["tcp_payload_bytes"] += tcp_len
        if time_epoch is not None:
            if stream["first_time_epoch"] is None:
                stream["first_time_epoch"] = time_epoch
            stream["last_time_epoch"] = time_epoch
        count_value(stream["src_ips"], record.get("src_ip"))
        count_value(stream["dst_ips"], record.get("dst_ip"))
        count_value(stream["src_ports"], record.get("src_port"))
        count_value(stream["dst_ports"], record.get("dst_port"))

    duration_sec = duration(first_time_epoch, last_time_epoch)
    summary: dict[str, object] = {
        "summary_type": "tcp",
        "packet_count": packet_count,
        "invalid_record_count": invalid_record_count,
        "first_time_epoch": first_time_epoch,
        "last_time_epoch": last_time_epoch,
        "duration_sec": duration_sec,
        "total_frame_bytes": total_frame_bytes,
        "total_tcp_payload_bytes": total_tcp_payload_bytes,
        "stream_count": len(streams),
        "retransmission_count": retransmission_count,
        "fast_retransmission_count": fast_retransmission_count,
        "out_of_order_count": out_of_order_count,
        "ack_rtt_count": len(ack_rtts),
        "ack_rtt_avg": sum(ack_rtts) / len(ack_rtts) if ack_rtts else None,
        "ack_rtt_min": min(ack_rtts) if ack_rtts else None,
        "ack_rtt_max": max(ack_rtts) if ack_rtts else None,
        "throughput_bps_frame": throughput_bps(total_frame_bytes, duration_sec),
        "throughput_bps_tcp_payload": throughput_bps(total_tcp_payload_bytes, duration_sec),
        "src_ip_counts": counter_dict(src_ip_counts),
        "dst_ip_counts": counter_dict(dst_ip_counts),
        "src_port_counts": counter_dict(src_port_counts),
        "dst_port_counts": counter_dict(dst_port_counts),
        "tcp_flags_counts": counter_dict(tcp_flags_counts),
        "streams": _finalize_streams(streams),
    }
    return write_json(output_file, summary)


def analyze_tcp_placeholder(packet_jsonl: Path) -> dict[str, object]:
    """Backward-compatible placeholder wrapper."""
    return {"packet_jsonl": str(packet_jsonl), "implemented": True}
